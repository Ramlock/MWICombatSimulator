// Inlines one of the game's own translation bundles into js/i18n.js, the way the en and zh bundles are inlined.
// The game loads every language but en lazily, one webpack chunk per language: its main chunk maps "./<lng>/index.js"
// to a chunk id, and the page's chunk URL map gives that chunk's file (static/js/<id>.<hash>.chunk.js).
// Download that chunk, then: node tools/extract-game-locale.mjs <chunk.js> <lng> <constName>
// The chunk runs in a bare vm context (no globals). The bundle is written between BEGIN/END markers before
// "const Wa = {", replacing an earlier copy, ASCII-escaped like the rest of the file.
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const [chunkPath, lng, constName] = process.argv.slice(2);
if (!chunkPath || !lng || !/^[A-Za-z_$][\w$]*$/.test(constName ?? '')) {
    console.error('Usage: node tools/extract-game-locale.mjs <chunk.js> <lng> <constName>');
    process.exit(2);
}
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const i18nPath = path.join(root, 'js', 'i18n.js');

const sandbox = { webpackJsonprpg_web: [] };
vm.runInNewContext(fs.readFileSync(chunkPath, 'utf8'), sandbox, { timeout: 5000 });
const modules = sandbox.webpackJsonprpg_web[0]?.[1] ?? {};
const ids = Object.keys(modules);
if (ids.length !== 1) throw new Error('expected one module in the chunk, got: ' + ids.join(','));
const moduleExports = {};
modules[ids[0]]({}, moduleExports, { r: () => {} });
const bundle = JSON.parse(JSON.stringify(moduleExports.default));
if (!bundle.itemNames || !bundle.monsterNames) throw new Error('not a translation bundle (no itemNames/monsterNames)');

let strings = 0;
(function walk(o) { for (const v of Object.values(o)) typeof v === 'object' && v !== null ? walk(v) : strings++; })(bundle);

const ascii = JSON.stringify(bundle, null, 4).replace(/[\u007f-￿]/g, (c) => '\\u' + c.charCodeAt(0).toString(16).padStart(4, '0'));
const begin = `    // BEGIN game ${lng} bundle (generated by tools/extract-game-locale.mjs)`;
const end = `    // END game ${lng} bundle`;
const block = begin + '\n    const ' + constName + ' = ' + ascii.replace(/\n/g, '\n    ') + ';\n' + end + '\n';

let src = fs.readFileSync(i18nPath, 'utf8');
const crlf = src.includes('\r\n');
src = src.replace(/\r\n/g, '\n');
const start = src.indexOf(begin);
if (start >= 0) {
    const stop = src.indexOf(end, start);
    src = src.slice(0, start) + block + src.slice(stop + end.length + 1);
} else {
    const at = src.indexOf('    const Wa = {');
    if (at < 0) throw new Error('"const Wa = {" not found in js/i18n.js');
    src = src.slice(0, at) + block + src.slice(at);
}
fs.writeFileSync(i18nPath, crlf ? src.replace(/\n/g, '\r\n') : src);
console.log(`${lng}: ${Object.keys(bundle).length} sections, ${strings} strings -> ${constName} in js/i18n.js`);
for (const k of ['itemNames', 'monsterNames', 'abilityNames', 'actionNames', 'skillNames', 'combatStats']) {
    console.log(`  ${k}: ${Object.keys(bundle[k] ?? {}).length}`);
}
